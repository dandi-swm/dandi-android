package com.dandi.nyummy.common.entity.tutorial

/**
 * 튜토리얼 식사 뒤에 이어지는 단계. 서버는 튜토리얼 식사 여부만 알므로 이 단계들은 기기에 남긴다.
 * 홈 소개, 카메라 버튼, 식사 기록 튜토리얼은 서버 값으로 정하므로 여기 없다.
 * 이름은 기기에 저장하는 값이므로 바꾸지 않는다.
 */
enum class TutorialStep {
    /** 튜토리얼 식사 뒤 홈에서 우편 버튼을 가리킨다. */
    HOME_MAIL,

    /** 우편함에서 보상 상자를 열어 보고 뒤로 가기로 홈에 돌아오게 한다. */
    MAILBOX,

    /** 우편함 단계 뒤 홈에서 마이룸 탭을 가리킨다. */
    HOME_ROOM_TAB,

    /** 마이룸에서 받은 아이템을 놓고 저장해 보게 한다. */
    ROOM,

    /** 마이룸을 저장하고 홈에 돌아왔을 때 방이 잘 저장됐다고 알린다. 저장하지 않고 마이룸 단계를 마치면 함께 마친다. */
    HOME_ROOM_SAVED,

    /** 홈에서 냐미 건강 이야기와 마침을 보인다. 건너뛰어도 남는 마지막 단계다. */
    HEALTH_STORY,
}
