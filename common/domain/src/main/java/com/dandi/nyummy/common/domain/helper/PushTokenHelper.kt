package com.dandi.nyummy.common.domain.helper

/**
 * 이 기기의 푸시(FCM) 토큰을 서버에 알리고 지우는 통로.
 *
 * 서버는 사용자당 토큰 하나를 두고 같은 사용자가 다시 보내면 교체하므로, 마지막으로 화면을 연 기기가 푸시를 받는다.
 * 사용자가 화면을 열 때마다, 로그인할 때, FCM이 새 토큰을 줄 때 보낸다.
 * 푸시를 받아 화면 없이 프로세스만 켜질 때는 보내지 않는다(받은 기기 전부가 등록과 토큰 재발급을 부르게 된다).
 */
interface PushTokenHelper {

    /**
     * 로그인한 상태면 [token](없으면 지금 기기의 토큰)을 서버에 등록한다.
     * 화면과 상관없이 백그라운드에서 보내고, 실패해도 알리지 않는다(다음에 화면을 열 때 다시 보낸다).
     */
    fun register(token: String? = null)

    /**
     * 이 기기의 푸시 토큰을 지운다(로그아웃). 서버 로그아웃이 실패해도 이 토큰으로는 더 이상 푸시가 오지 않는다.
     * 다음 로그인 때는 새 토큰이 만들어져 [register]된다.
     * 지우기가 끝날 때까지 기다린다. 끝나기 전에 다시 로그인해 새 등록이 먼저 실행되면, 서버에 곧 무효가 될 토큰이 남기 때문이다.
     */
    suspend fun deleteToken()
}
